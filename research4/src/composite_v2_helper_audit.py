"""Read-only helper contribution evidence; no action synthesis or model calls."""
from copy import deepcopy
from .io_utils import digest
from .composite_generalized_world import World,expected_analysis
from .composite_generalized_novelty import causal_core,material_execution_signature
from .composite_v2_trace_audit import audit_trace

READER='v2-causal-helper-evidence-v1'
MEASUREMENT='outcome_relevant_core_live_inputs_paired_groups_v3_operation_consumption'
_KEY=object()


class HelperEvidence:
    def __init__(self,receipt,key=None):
        if key is not _KEY:raise PermissionError('Derive helper evidence from recorded replay')
        self._receipt=deepcopy(receipt);self._key=key

    def receipt(self):return deepcopy(self._receipt)


class TrainingExposure:
    def __init__(self,source,data,programs,fixture,key=None):
        if key is not _KEY:raise PermissionError('Derive exposure from complete recorded training episodes')
        fingerprints=set()
        for program in programs:
            writes=[i for i,step in enumerate(program['steps']) if step['op']=='patch']
            for returned in [False,True]:
                value=causal_core(program,writes,returned).get('fingerprint')
                if value is not None:fingerprints.add(value)
        self.source=source;self.data=data;self.fixture=fixture
        self.fingerprints=frozenset(fingerprints);self._key=key


def training_exposure(episodes,rows,design,source_commit,data_release_sha256,*,public_fixture=False,cohort_manifest=None,_data_key=None):
    """Re-audit all training episodes before constructing the exclusion set.

    The public path handles existing unit examples only and is never scientific
    evidence. No helper definition or answer is generated by this reader.
    """
    import re
    if not re.fullmatch('[0-9a-f]{40}',source_commit) or not re.fullmatch('[0-9a-f]{64}',data_release_sha256):
        raise ValueError('Exact training source and data binding required')
    if public_fixture:
        if not episodes or any(e['scene'].get('role')!='public_design_fixture'
                               or not e['scene'].get('identity_seed','').startswith('unit:') for e in episodes):
            raise PermissionError('Only public unit examples may bypass complete cohort audit')
    else:
        from .composite_generalized_audit import audit_cohort
        if _data_key is not _KEY:raise PermissionError('Read the source-bound complete training archive')
        if not isinstance(cohort_manifest,dict) or cohort_manifest.get('role')!='training':
            raise PermissionError('Exact complete training cohort manifest required')
        audit_cohort(episodes,rows,cohort_manifest,design,reference_replay=True)
    programs=[p for episode in episodes for p in episode.get('helper_definitions',{}).values()]
    return TrainingExposure(source_commit,data_release_sha256,programs,public_fixture,_KEY)


def training_exposure_from_archive(raw,root,source_commit,*,qualification_evidence=None):
    import io,json,zipfile,hashlib
    from pathlib import Path
    from .composite_v2_model_contract import validate_model_metadata,load_training_export
    from .composite_generalized_data import require_runtime
    from .io_utils import read
    context=validate_model_metadata(root,source_commit)
    require_runtime()
    rows,release=load_training_export(raw,context,qualification_evidence=qualification_evidence)
    with zipfile.ZipFile(io.BytesIO(raw)) as stream:
        episode_bytes=stream.read('training/EPISODES.json')
        if hashlib.sha256(episode_bytes).hexdigest()!=release['cohorts']['training']['files']['EPISODES.json']:
            raise ValueError('Exact complete training episode bytes changed')
        episodes=json.loads(episode_bytes)
        manifest=json.loads(stream.read('training/COHORT_MANIFEST.json'))
    return training_exposure(episodes,rows,read(Path(root)/'config/composite_generalization_amendment_v2.json'),
        source_commit,digest(release),cohort_manifest=manifest,_data_key=_KEY)


def read_helper_evidence(record,scene,source_commit,design,exposure=None,tokenizers=None,*,
                         public_fixture=False,fixture_tokenizers=None):
    if design['operational_transfer_criteria']['measurement_profile']!=MEASUREMENT:
        raise PermissionError('Use the reviewed operation-aware measurement profile')
    raw=audit_trace(record,scene,source_commit,tokenizers,public_fixture=public_fixture,
                    fixture_tokenizers=fixture_tokenizers)
    if exposure is not None and (not isinstance(exposure,TrainingExposure) or exposure._key is not _KEY
                                 or exposure.source!=source_commit or (exposure.fixture and not public_fixture)):
        raise PermissionError('Unverified, foreign or public-only training exposure')
    # Reconstruct only the exact recorded calls. Locate the first authoritative
    # record-effect transition, including a transition inside a helper call.
    world=World(scene);commit_index=None
    primitive=world.engine._primitive
    def watched(op,args):
        nonlocal commit_index
        before=world.continuity
        result=primitive(op,args)
        if not before and world.continuity:commit_index=len(world.engine.trace)-1
        return result
    world.engine._primitive=watched
    for step in record['trace']:world.step(step['executed_action'])
    for field,value in [('primitive_trace',world.engine.trace),('helper_calls',world.helper_calls),
                        ('helper_definitions',world.engine.definitions)]:
        if digest(record[field])!=digest(value):raise ValueError('Helper evidence differs from exact replay')
    # At the actual transition, each required field has a last *changing*
    # writer. Redundant writes and values overwritten before this boundary
    # cannot manufacture contribution. The source predicates are recomputed
    # directly; no caller success/relevance booleans are consumed.
    required={}
    for i,target in enumerate(world.analysis_ids):
        fields=expected_analysis(scene.mechanism,world.documents[world.source_ids[i]]['data'])
        if scene.mechanism=='multi_object_transformation':
            required[(target,'total')]=fields['total']
            required[(world.auxiliary_ids[i],'peak')]=fields['peak']
        else:
            required.update({(target,key):value for key,value in fields.items()})
    last={};values={}
    if commit_index is not None:
        for index,entry in enumerate(world.engine.trace[:commit_index+1]):
            if entry['op']!='patch' or entry['result'].get('status')!='recorded':continue
            target=entry['arguments']['identifier'];before=entry['record_before'];after=entry['record_after']
            for (identifier,key),expected in required.items():
                if identifier!=target:continue
                if key in after:values[(identifier,key)]=after[key]
                if digest({'present':key in before,'value':before.get(key)})!=digest({'present':key in after,'value':after.get(key)}):
                    last[(identifier,key)]=index
        if any(key not in values or digest(values[key])!=digest(value) for key,value in required.items()):
            raise ValueError('Recorded effect transition does not satisfy independent record predicates')
    relevant=set(last.values()) if commit_index is not None else set()
    helpers=[];unknown=False;unrolled=0
    for name,program in world.engine.definitions.items():
        signatures=set();sizes=[];fingerprints=set();unresolved_return=False;calls=[]
        attempts=sum(isinstance(step['executed_action'],dict)
            and step['executed_action'].get('tool') in ['define','invoke']
            and step['executed_action'].get('arguments',{}).get('name')==name for step in record['trace'])
        for call in world.helper_calls:
            if call['name']!=name:continue
            start,end=call['trace_start'],call['trace_end'];trace=world.engine.trace[start:end]
            effects=[index-start for index in relevant if start<=index<end]
            signature,core=material_execution_signature(program,trace,effects)
            if signature is not None:
                signatures.add(signature);sizes.append(len(core['core_program']['steps']));fingerprints.add(core['fingerprint'])
            return_core=causal_core(program,[],verified_return_used=True)
            # Value equality is not provenance. The present ABI has no explicit
            # reference from a later model action to a prior helper result.
            maybe_return=(not effects and return_core.get('eligible_for_compositional_transfer_claim') is True
                          and program['steps'][-1]['op'] not in ['patch'])
            unresolved_return=unresolved_return or maybe_return
            calls.append({'trace_start':start,'trace_end':end,'outcome_relevant_write_steps':effects,
                          'material_signature':signature,'causal_core':core,
                          'return_use':'unknown_no_explicit_result_reference' if maybe_return else 'not_credited'})
        novelty=None if exposure is None else bool(fingerprints) and not bool(fingerprints&exposure.fingerprints)
        savings=sum(sizes)-attempts
        qualifies=len(signatures)>=2 and savings>0 and novelty is True
        unknown=unknown or unresolved_return or (len(signatures)>=2 and savings>0 and novelty is None)
        unrolled+=sum(sizes)
        helpers.append({'name':name,'calls':calls,'distinct_consumed_bindings':len(signatures),
            'pruned_unrolled_decisions':sum(sizes),'actual_definition_and_invocation_decisions':attempts,
            'net_decisions_saved':savings,'training_exposure_excluded':novelty,
            'verified_write_helper_criterion_met':qualifies})
    decisions=sum(isinstance(s['executed_action'],dict) and s['executed_action'].get('tool') in ['define','invoke'] for s in record['trace'])
    success=any(h['verified_write_helper_criterion_met'] for h in helpers) and unrolled>decisions
    if not success and unknown:success=None
    receipt={'reader':READER,'trace_sha256':digest(record),'source_commit':source_commit,
        'measurement_profile':MEASUREMENT,'success':success,'helpers':helpers,
        'actual_effect_transition_primitive_index':commit_index,'case_net_decisions_saved':unrolled-decisions,
        'training_data_release_sha256':None if exposure is None else exposure.data,
        'training_exposure_sha256':None if exposure is None else digest(sorted(exposure.fingerprints)),
        'raw_evidence_audited':raw['raw_evidence_audited'],'public_fixture_test_mode':public_fixture,
        'caller_supplied_relevance_used':False,'value_equality_is_return_use_proof':False,
        'model_forwards':0,'optimizer_updates':0,'heldout_content_read':False}
    return HelperEvidence(receipt,_KEY)


def bound_helper_receipt(value,trace_sha256,source_commit,measurement_profile,data_release_sha256=None):
    if not isinstance(value,HelperEvidence) or value._key is not _KEY:return None
    proof=value.receipt()
    if (proof['trace_sha256']!=trace_sha256 or proof['source_commit']!=source_commit
        or proof['measurement_profile']!=measurement_profile or proof['raw_evidence_audited'] is not True
        or proof['public_fixture_test_mode'] is not False
        or proof['training_data_release_sha256']!=data_release_sha256):return None
    return proof
